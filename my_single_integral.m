function Q = my_single_integral(f, A, B)
x = [-0.906179845938664,-0.538469310105683,0,0.538469310105683,0.906179845938664];
w = [0.2369268850561891,0.4786286704993665,0.5688888888888889,0.4786286704993665,0.2369268850561891];
t = ((B - A)/2) * x + (A + B)/2;
Q = (B - A)/2 * sum(w .* arrayfun(f, t));
end